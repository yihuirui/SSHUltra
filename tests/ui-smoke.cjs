const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const { createFixture } = require('./fixture.cjs');

const project = path.resolve(__dirname, '..');
const waitFor = async (predicate, timeout = 10000) => { const end = Date.now() + timeout; while (Date.now() < end) { if (await predicate()) return; await new Promise(r => setTimeout(r, 50)); } throw new Error('UI evidence timed out'); };
async function run() {
  const fixture = await createFixture();
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'harbor-ui-'));
  const output = path.join(project, 'test-results'); fs.mkdirSync(output, { recursive: true });
  let app;
  const report = { checks: [], pageErrors: [], screenshots: [], packaged: Boolean(process.env.HARBOR_PACKAGED_APP) };
  try {
    const env = { ...process.env, HARBOR_TEST_MODE: '1', HARBOR_DATA_DIR: path.join(temp, 'userdata') };
    delete env.ELECTRON_RUN_AS_NODE;
    const options = { args: process.env.HARBOR_PACKAGED_APP ? [] : [project], env, timeout: 30000 };
    if (process.env.HARBOR_PACKAGED_APP) options.executablePath = process.env.HARBOR_PACKAGED_APP;
    app = await electron.launch(options);
    await app.evaluate(({ dialog }) => {
      globalThis.__harborTest = { dialogs: [], batchResponse: 1, upload: '', download: '' };
      dialog.showMessageBox = async (_window, options) => {
        globalThis.__harborTest.dialogs.push(options);
        return { response: options.title === '确认批量发送' ? globalThis.__harborTest.batchResponse : 1 };
      };
      dialog.showMessageBoxSync = () => 1;
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [globalThis.__harborTest.upload] });
      dialog.showSaveDialog = async () => ({ canceled: false, filePath: globalThis.__harborTest.download });
    });
    const page = await app.firstWindow();
    page.on('pageerror', e => report.pageErrors.push(e.message));
    await page.getByText('每个连接，都井然有序。').waitFor();
    const screenshot = async name => { const file = path.join(output, `${report.packaged ? 'packaged-' : ''}${name}.png`); await page.screenshot({ path: file }); report.screenshots.push(file); };
    await screenshot('welcome');
    const prefs = await app.evaluate(({ BrowserWindow }) => { const p = BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences(); return { sandbox: p.sandbox, contextIsolation: p.contextIsolation, nodeIntegration: p.nodeIntegration }; });
    assert.deepEqual(prefs, { sandbox: true, contextIsolation: true, nodeIntegration: false });
    assert.equal(await page.evaluate(() => typeof window.require), 'undefined'); report.checks.push('Sandbox and context isolation enabled; Node unavailable in renderer');
    for (const name of ['Web 01 · 测试', 'Web 02 · 测试', 'Database · 测试']) {
      await page.getByRole('button', { name: '新建连接' }).click();
      const form = page.getByRole('dialog', { name: 'SSH 连接', exact: true });
      await form.getByLabel('连接名称', { exact: true }).fill(name);
      await form.getByLabel('分组', { exact: true }).fill('本机隔离测试');
      await form.getByLabel('主机地址', { exact: true }).fill('127.0.0.1');
      await form.getByLabel('端口', { exact: true }).fill(String(fixture.port));
      await form.getByLabel('用户名', { exact: true }).fill('ops');
      await form.getByLabel('密码', { exact: true }).fill(fixture.password);
      await form.getByRole('button', { name: '保存并连接' }).click();
      await page.getByRole('tab', { name }).waitFor();
      await page.getByLabel(`批量目标 ${name}`, { exact: true }).waitFor();
    }
    report.checks.push('Three real SSH connections created through UI');
    const hostDialogs = await app.evaluate(() => globalThis.__harborTest.dialogs.filter(d => d.title === '确认 SSH 主机指纹'));
    assert.equal(hostDialogs.length, 1); assert.match(hostDialogs[0].detail, /SHA256:/);
    report.checks.push('First-use trust dialog shown once for shared host');
    await page.getByRole('button', { name: '双栏分屏', exact: true }).click();
    assert.equal(await page.locator('[data-testid="terminal-pane"]:visible').count(), 2);
    await page.getByRole('button', { name: '四宫格分屏', exact: true }).click();
    assert.equal(await page.locator('[data-testid="terminal-pane"]:visible').count(), 3);
    await page.getByRole('tab', { name: 'Web 01 · 测试', exact: true }).click();
    await page.getByLabel('批量目标 Web 01 · 测试', { exact: true }).check();
    await page.getByLabel('批量目标 Web 02 · 测试', { exact: true }).check();
    await page.getByRole('textbox', { name: '批量命令', exact: true }).fill('printf "UI_BATCH_VERIFIED\\n"');
    await app.evaluate(() => { globalThis.__harborTest.batchResponse = 0; });
    await page.getByRole('button', { name: '预览并发送', exact: true }).click();
    await waitFor(async () => (await app.evaluate(() => globalThis.__harborTest.dialogs.filter(d => d.title === '确认批量发送').length)) === 1);
    assert.equal(fixture.inputs.filter(x => x.includes('UI_BATCH_VERIFIED')).length, 0);
    await app.evaluate(() => { globalThis.__harborTest.batchResponse = 1; });
    await page.getByRole('button', { name: '预览并发送', exact: true }).click();
    await waitFor(() => fixture.inputs.filter(x => x.includes('UI_BATCH_VERIFIED')).length === 2);
    const batchDialogs = await app.evaluate(() => globalThis.__harborTest.dialogs.filter(d => d.title === '确认批量发送'));
    assert.match(batchDialogs[1].message, /2 个 SSH/); assert.ok(!batchDialogs[1].detail.includes('Database'));
    report.checks.push('Split layouts render 2/3 real terminals; cancel sends nothing; confirm sends only 2 selected sessions');
    const pane = page.locator('[data-testid="terminal-pane"].focused');
    await pane.locator('.xterm-helper-textarea').focus();
    await page.keyboard.type('printf "INTERACTIVE_OK\\n"'); await page.keyboard.press('Enter');
    await waitFor(() => fixture.inputs.join('').includes('INTERACTIVE_OK'));
    await page.getByLabel('批量命令', { exact: true }).fill('uname -a');
    report.checks.push('Interactive terminal keyboard input reaches SSH server');
    await page.getByTitle('下载 welcome.txt', { exact: true }).waitFor();
    const upload = path.join(temp, 'upload-proof.txt'); const download = path.join(temp, 'download-proof.txt');
    fs.writeFileSync(upload, 'UI upload/download round trip\n中文检查\n');
    await app.evaluate((_electron, paths) => { globalThis.__harborTest.upload = paths.upload; globalThis.__harborTest.download = paths.download; }, { upload, download });
    await page.getByRole('button', { name: '上传文件', exact: true }).click();
    await page.getByTitle('下载 upload-proof.txt', { exact: true }).waitFor();
    assert.equal(fs.readFileSync(path.join(fixture.root, 'upload-proof.txt'), 'utf8'), fs.readFileSync(upload, 'utf8'));
    await page.getByTitle('下载 upload-proof.txt', { exact: true }).click();
    await waitFor(() => fs.existsSync(download)); assert.deepEqual(fs.readFileSync(download), fs.readFileSync(upload));
    report.checks.push('SFTP upload/download via native file chooser API round-trips exact bytes');
    await page.getByRole('button', { name: 'logs', exact: true }).click();
    await waitFor(async () => (await page.getByLabel('远程路径', { exact: true }).inputValue()) === '/logs');
    await page.getByTitle('上级目录', { exact: true }).click();
    await waitFor(async () => (await page.getByLabel('远程路径', { exact: true }).inputValue()) === '/');
    await pane.getByTitle('搜索终端 ⌘F', { exact: true }).click();
    await pane.getByRole('textbox', { name: '搜索终端', exact: true }).fill('UI_BATCH_VERIFIED');
    await pane.getByRole('textbox', { name: '搜索终端', exact: true }).press('Enter');
    assert.equal(await pane.getByText('未找到', { exact: true }).count(), 0);
    await pane.getByTitle('关闭搜索', { exact: true }).click();
    const transcript = path.join(temp, 'transcript.txt');
    await app.evaluate((_electron, file) => { globalThis.__harborTest.download = file; }, transcript);
    await pane.getByTitle('导出回滚内容', { exact: true }).click();
    await waitFor(() => fs.existsSync(transcript));
    assert.ok(fs.readFileSync(transcript, 'utf8').includes('UI_BATCH_VERIFIED'));
    report.checks.push('Directory navigation, terminal search, and scrollback export work');
    await page.getByTitle('关闭提示', { exact: true }).click().catch(() => {});
    await screenshot('workspace');
    const size = await page.evaluate(() => ({ w: window.innerWidth, h: window.innerHeight }));
    assert.ok(size.w >= 1000);
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1050, 720));
    await page.waitForTimeout(300); await screenshot('compact');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    report.checks.push('Compact 1050×720 layout has no horizontal document overflow');
    await page.getByRole('button', { name: '新窗口', exact: true }).click();
    await waitFor(() => app.windows().length === 2);
    const second = app.windows().find(p => p !== page);
    await second.getByText('每个连接，都井然有序。').waitFor();
    assert.equal(await second.getByRole('tab').count(), 0);
    assert.equal(await second.getByTitle('连接 ops@127.0.0.1', { exact: true }).count(), 3);
    report.checks.push('New window has independent sessions and shared saved profiles');
    await second.close();
    const config = fs.readFileSync(path.join(temp, 'userdata', 'workspace.json'), 'utf8');
    assert.equal(JSON.parse(config).profiles.length, 3); assert.ok(!config.includes(fixture.password));
    report.checks.push('Persisted profiles contain no entered password');
    // Regression: completion of an upload from A must not replace B's directory view.
    await page.getByRole('tab', { name: 'Web 01 · 测试', exact: true }).click();
    await page.getByRole('button', { name: 'logs', exact: true }).click();
    await waitFor(async () => (await page.getByLabel('远程路径', { exact: true }).inputValue()) === '/logs');
    const slowUpload = path.join(temp, 'slow-upload.bin'); fs.writeFileSync(slowUpload, Buffer.alloc(512 * 1024, 42));
    await app.evaluate((_electron, file) => { globalThis.__harborTest.upload = file; }, slowUpload);
    fixture.setWriteDelay(70);
    await page.getByRole('button', { name: '上传文件', exact: true }).click();
    await waitFor(() => fs.existsSync(path.join(fixture.root, 'logs', 'slow-upload.bin')));
    await page.getByRole('tab', { name: 'Web 02 · 测试', exact: true }).click();
    await waitFor(async () => (await page.getByLabel('远程路径', { exact: true }).inputValue()) === '/');
    await page.getByRole('status').filter({ hasText: '上传完成 · 512.0 KB' }).waitFor();
    await page.waitForTimeout(250); // Allow any erroneous stale refresh to settle before asserting.
    assert.equal(await page.getByLabel('远程路径', { exact: true }).inputValue(), '/');
    assert.equal(await page.getByTitle('下载 slow-upload.bin', { exact: true }).count(), 0);
    fixture.setWriteDelay(0);
    report.checks.push('Finishing a background upload cannot replace another session’s file view');
    await page.getByLabel('批量目标 Database · 测试', { exact: true }).check();
    await page.getByTitle('关闭 Database · 测试', { exact: true }).click();
    assert.equal(await page.getByLabel('批量目标 Database · 测试', { exact: true }).count(), 0);
    assert.equal(await page.getByRole('tab').count(), 2);
    report.checks.push('Closing a session removes it from batch targets without closing other sessions');
    assert.deepEqual(report.pageErrors, []);
    report.checks.push('No renderer JavaScript errors');
    console.log(JSON.stringify(report, null, 2));
    fs.writeFileSync(path.join(output, report.packaged ? 'packaged-ui-report.json' : 'ui-report.json'), JSON.stringify(report, null, 2));
  } catch (error) {
    if (app) { try { await app.windows()[0]?.screenshot({ path: path.join(output, 'failure.png') }); } catch {} }
    throw error;
  } finally {
    if (app) await app.close();
    await fixture.close();
    fs.rmSync(temp, { recursive: true, force: true });
  }
}
run().catch(error => { console.error(error); process.exitCode = 1; });
